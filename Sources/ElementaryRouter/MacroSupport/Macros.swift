/// Declares a typed route table and generates the public API for working with it.
///
/// Apply this macro to a type that contains `@Route`, `@Layout`, `@NotFound`, and `@RouteError`
/// declarations. The macro generates:
///
/// - `RouteView`: the typed view tree rendered by this route set, with a nested outlet enum
///   per layout, such as `RouteView.ShellOutlet`, that selects the layout's matched child and
///   is rendered through `Outlet<_RouteOutlet<RouteView.ShellOutlet>>`
/// - `RouteSet`: the compiled route tree plus route handles, `router()` to create either
///   `Router<RouteView>` or `HashRouter<RouteView>` for them, and one typed destination factory
///   per `@Route`, such as `profile(lang:profileId:tab:hash:)`, returning
///   `RouteDestination<RouteView>`
/// - `Handles`: low-level route handles for each declared route and layout
/// - `Provider`: a route-set-specific environment provider for a route set and its router
/// - `RouterView`: a route-set-specific view that renders the current route, either for a route
///   set and router it creates once per mounted lifetime, or for a supplied pair
/// - `Link`: a route-set-specific navigation view for a `RouteDestination<RouteView>`
/// - `routes()`: builds a route set
///
/// Destination factories take the route's path values, wildcard value, and query values with
/// their declared types, followed by the query values of the layouts above the route, so missing
/// or mistyped arguments do not compile. A query name shared by a route and its layouts is one
/// argument, required when any declaration has no default. A factory throws
/// `RouteMatchError` when the values cannot produce a URL that resolves back to the route; a
/// route without path or wildcard values and with only built-in query types gets a non-throwing
/// factory. Layouts get no factory, because they never match a location on their own.
///
/// Each `routes()` call registers a new set of handles. Destinations and handles from one route
/// set are rejected by routers created from another, so keep the route set that created a
/// router and pass both to `Provider` or `RouterView`.
///
/// `mode` selects whether generated links and routers use browser path routing or hash routing.
///
/// `basePath` is the document path prefix a path-mode app is served under, such as
/// `"/my-app"` for `https://example.github.io/my-app/`. Routes stay declared from `/`: the router
/// matches the document path below the prefix, a document path outside it renders `@NotFound`,
/// and `router()`, `RouteSet.href(to:)`, `Link`, and `RouteLink` prefix every href and history
/// entry with it, including those of mounted features. Leading and trailing slashes are optional,
/// and `""` or `"/"` mean no base path. It is a string literal of URL path segments, compared
/// byte for byte with the percent-encoded `location.pathname`. Hash mode rejects it, because
/// fragment hrefs already resolve against the document URL.
///
/// ## Features and mounts
///
/// A `@Routes` struct with exactly one generic parameter, such as
/// `struct ShopRoutes<Root: View>`, declares a mountable feature instead of a route set. Its
/// routes and layouts are registered into a host's route tree, whose `RouteView` is `Root`:
///
/// - `RouteView`, its outlet enums, and `Handles` are generated as for a route set
/// - `RouteSet` holds the feature's handles in the host tree, with one destination factory per
///   `@Route` returning `RouteDestination<Root>`
/// - `@Environment(ShopRoutes<Root>.RouteSet.self)` reads the route set inside the host's `Provider`
/// - `_register(into:under:wrap:)` registers the feature under a host mount record
///
/// A feature has no router, `Provider`, `RouterView`, `Link`, `routes()`, `@NotFound`,
/// `@RouteError`, or `mode`; the host owns them. A host mounts a feature with `@Mount`.
@attached(
  member,
  names: named(RouteView),
  named(RouteSet),
  named(_routerEnvironmentKey),
  named(_routeSetEnvironmentKey),
  named(Handles),
  named(Provider),
  named(RouterView),
  named(Link),
  named(routes),
  named(_register)
)
public macro Routes(mode: RoutesMode = .path, basePath: String = "") =
  #externalMacro(module: "ElementaryRouterMacros", type: "RoutesMacro")

/// Selects the router mode generated by `@Routes`.
public enum RoutesMode {
  /// Uses normal browser paths such as `/users/42`.
  case path
  /// Uses fragment-based URLs such as `/#/users/42`.
  case hash
}

